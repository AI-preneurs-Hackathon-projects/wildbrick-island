import assert from 'node:assert/strict';
import {createVercelHandler} from '../server/vercel-handler.js';
const secret = 'test-secret-'.repeat(4);
let calls = [], sequence = 0, time = 1800000000;
const env = {SESSION_SECRET: secret, OPENAI_API_KEY: 'test-only-never-sent'};
const worker = {async fetch(request, env, ctx) {calls.push({request, env, ctx}); return Response.json({ok: true});}};
const handler = createVercelHandler({worker, getDb: () => ({marker: 'database'}), env, now: () => time, uuid: () => `00000000-0000-4000-8000-${String(++sequence).padStart(12,'0')}`});
const request = (path='/api/arena/join', headers={}, method='POST') => new Request(`https://game.example${path}`, {method, headers: {origin: 'https://game.example', ...headers}, ...(method === 'POST' ? {body:'{}'} : {})});
let response = await handler(request(undefined, {'oai-authenticated-user-id':'victim','cf-connecting-ip':'spoof','cf-access-jwt-assertion':'spoof'}));
assert.equal(response.status,200);
const cookie = response.headers.get('set-cookie');
assert.match(cookie,/HttpOnly; Secure; SameSite=Lax/);
assert.match(cookie,/^__Host-brickwild-guest=/);
const principal = calls.at(-1).request.headers.get('oai-authenticated-user-id');
assert.match(principal,/^vercel-guest:/);
assert.notEqual(principal,'victim');
assert.equal(calls.at(-1).request.headers.get('cf-access-jwt-assertion'),null);
assert.equal(calls.at(-1).env.DB.marker,'database');
const saved = cookie.split(';')[0];
response = await handler(request(undefined,{cookie:saved}));
assert.equal(response.headers.get('set-cookie'),null);
assert.equal(calls.at(-1).request.headers.get('oai-authenticated-user-id'),principal);
response = await handler(request(undefined,{cookie:saved+'x'}));
assert.ok(response.headers.get('set-cookie'));
assert.notEqual(calls.at(-1).request.headers.get('oai-authenticated-user-id'),principal);
response = await handler(request(undefined,{cookie:`${saved}; ${saved}`}));
assert.ok(response.headers.get('set-cookie'));
time += 31*86400;
response = await handler(request(undefined,{cookie:saved}));
assert.ok(response.headers.get('set-cookie'));
for (const headers of [{origin:'https://evil.example'},{'sec-fetch-site':'cross-site'},{'sec-fetch-site':'same-site'},{origin:'null'}]) assert.equal((await handler(request(undefined,headers))).status,403);
const before = calls.length;
for (const path of ['/api/generate','/api/transcribe']) assert.equal((await handler(request(path))).status,503);
for (const path of ['/api/generation-status?verify=1','/api/transcription-status']) assert.deepEqual(await (await handler(request(path,{},'GET'))).json(),{configured:false});
assert.equal(calls.length,before);
env.ENABLE_PUBLIC_GENERATION='true';
assert.equal((await handler(request('/api/generate'))).status,200);
const missing = createVercelHandler({worker,getDb:()=>{throw new Error('secret-database-url');},env});
response=await missing(request());
assert.equal(response.status,503);assert.ok(!(await response.text()).includes('secret-database-url'));
const bad = createVercelHandler({worker,getDb:()=>({}),env:{SESSION_SECRET:'short'}});
assert.equal((await bad(request())).status,503);
console.log('Vercel handler: signed guest continuity, tampering/expiry, header trust, origin protection, feature gates and sanitized failure checks passed.');
